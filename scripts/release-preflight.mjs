import fs from 'node:fs';
const r=JSON.parse(fs.readFileSync('release-config.json','utf8'));
const cap=JSON.parse(fs.readFileSync('capacitor.config.json','utf8'));
if(!r.bundleId||!/^\d+$/.test(r.ascAppId||'')||!r.profileReference)throw Error('Apple registration confirmation is incomplete: bundleId, ascAppId, profileReference required');
if(r.bundleId!==cap.appId||r.appName!==cap.appName)throw Error('Confirmed release identity does not match Capacitor');
const project=fs.readFileSync('ios/App/App.xcodeproj/project.pbxproj','utf8');
if(!project.includes('PRODUCT_BUNDLE_IDENTIFIER = '+r.bundleId+';'))throw Error('Xcode bundle ID differs');
const ci=fs.readFileSync('codemagic.yaml','utf8');
if(ci.includes('TSURIIKO_PROFILE_PENDING'))throw Error('Replace the pending provisioning profile reference after confirmation');
if(process.env.ASC_APP_ID!==r.ascAppId)throw Error('ASC_APP_ID must match confirmed app record');
console.log('Release identity verified; no credential values printed');
